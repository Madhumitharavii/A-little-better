/**
 * Trains the emotion classifier head (softmax regression on MiniLM
 * embeddings) and writes src/features/ai/emotionHead.json.
 *
 *   npm run train:emotion
 *
 * 1. Embeds the training sentences with the same on-device model the app uses.
 * 2. Leakage check: aborts if any training sentence is a near-duplicate
 *    (cosine ≥ 0.9) of an evaluation sentence.
 * 3. Picks the L2 strength and confidence threshold by 5-fold stratified
 *    cross-validation on the TRAINING data only — the evaluation set is
 *    never looked at here.
 * 4. Retrains on all training data and saves the weights.
 */
import path from 'node:path';
import fs from 'node:fs';
import { pipeline, env, type FeatureExtractionPipeline } from '@huggingface/transformers';
import { cosine, classifyEmotionWithHead, stratifiedFolds, trainSoftmax, type Vector } from '../../src/features/ai/ml';
import { EMOTION_TRAIN } from './trainingData';
import { EMOTION_EVAL } from '../../tests/eval/emotionDataset';

env.allowRemoteModels = false;
env.localModelPath = path.resolve('public/models') + '/';
const model = (await pipeline('feature-extraction', 'Xenova/all-MiniLM-L6-v2', { dtype: 'q8' })) as FeatureExtractionPipeline;
const embed = async (texts: string[]): Promise<Vector[]> => {
  const out = await model(texts, { pooling: 'mean', normalize: true });
  const data = out.data as Float32Array;
  const dims = out.dims[1] as number;
  return texts.map((_, i) => Array.from(data.subarray(i * dims, (i + 1) * dims)));
};

const labels = Object.keys(EMOTION_TRAIN) as (keyof typeof EMOTION_TRAIN)[];
const texts = labels.flatMap((l) => EMOTION_TRAIN[l]);
const y = labels.flatMap((l, c) => EMOTION_TRAIN[l].map(() => c));
const X = await embed(texts);

// ── leakage check ──
const evalVectors = await embed(EMOTION_EVAL.map((e) => e.text));
const leaks: string[] = [];
X.forEach((x, i) => evalVectors.forEach((e, j) => {
  const s = cosine(x, e);
  if (s >= 0.9) leaks.push(`${s.toFixed(2)}  "${texts[i]}"  ~  "${EMOTION_EVAL[j].text}"`);
}));
if (leaks.length) {
  console.error('Training sentences too close to evaluation sentences:\n' + leaks.join('\n'));
  process.exit(1);
}
const maxOverlap = Math.max(...X.flatMap((x) => evalVectors.map((e) => cosine(x, e))));
console.log(`${texts.length} training sentences, ${labels.length} classes. Closest train↔eval pair: cosine ${maxOverlap.toFixed(2)} (limit 0.90)`);

// ── 5-fold cross-validation (training data only) ──
const K = 5;
const folds = stratifiedFolds(y, K);
const L2S = [1e-4, 3e-4, 1e-3, 3e-3, 1e-2];
const THRESHOLDS = [0, 0.3, 0.4, 0.5];
const neutral = labels.indexOf('neutral');

function macroF1(truth: number[], pred: number[]) {
  return labels.reduce((s, _, c) => {
    const tp = truth.filter((t, i) => t === c && pred[i] === c).length;
    const p = pred.filter((x) => x === c).length;
    const a = truth.filter((x) => x === c).length;
    const prec = p ? tp / p : 0;
    const rec = a ? tp / a : 0;
    return s + (prec + rec ? (2 * prec * rec) / (prec + rec) : 0);
  }, 0) / labels.length;
}

let best = { l2: 0, threshold: 0, f1: -1, acc: 0 };
for (const l2 of L2S) {
  const preds = new Map(THRESHOLDS.map((t) => [t, new Array<number>(y.length).fill(-1)]));
  for (let f = 0; f < K; f++) {
    const tr = y.map((_, i) => i).filter((i) => folds[i] !== f);
    const head = trainSoftmax(tr.map((i) => X[i]), tr.map((i) => y[i]), labels, { l2 });
    y.forEach((_, i) => {
      if (folds[i] !== f) return;
      for (const t of THRESHOLDS) {
        const e = classifyEmotionWithHead(X[i], head, t).emotion;
        preds.get(t)![i] = e ? labels.indexOf(e) : neutral;
      }
    });
  }
  for (const t of THRESHOLDS) {
    const p = preds.get(t)!;
    const f1 = macroF1(y, p);
    const acc = y.filter((v, i) => v === p[i]).length / y.length;
    console.log(`  l2=${l2.toExponential(0)}  threshold=${t}  CV accuracy ${(acc * 100).toFixed(1)}%  macro-F1 ${f1.toFixed(3)}`);
    if (f1 > best.f1 + 1e-9) best = { l2, threshold: t, f1, acc };
  }
}
console.log(`Chosen: l2=${best.l2}, threshold=${best.threshold} (CV accuracy ${(best.acc * 100).toFixed(1)}%, macro-F1 ${best.f1.toFixed(3)})`);

// ── final model on all training data ──
const head = trainSoftmax(X, y, labels, { l2: best.l2 });
const round = (v: number) => Math.round(v * 1e5) / 1e5;
const out = {
  about: 'Emotion classifier head: softmax regression on all-MiniLM-L6-v2 embeddings. Generated by scripts/emotion/train.ts — do not edit by hand.',
  embeddingModel: 'Xenova/all-MiniLM-L6-v2',
  trainingSentences: texts.length,
  l2: best.l2,
  minConfidence: best.threshold,
  cv: { folds: K, accuracy: round(best.acc), macroF1: round(best.f1) },
  labels: head.labels,
  W: head.W.map((r) => r.map(round)),
  b: head.b.map(round),
};
const file = path.resolve('src/features/ai/emotionHead.json');
fs.writeFileSync(file, JSON.stringify(out) + '\n');
console.log(`Saved ${path.relative(process.cwd(), file)} (${(fs.statSync(file).size / 1024).toFixed(0)} KB)`);
