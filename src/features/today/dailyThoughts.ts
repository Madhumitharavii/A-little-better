/** Days since a fixed start, counted on the LOCAL calendar (so it changes at your midnight). */
function localDayNumber(date: Date): number {
  return Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
}

const gcd = (a: number, b: number): number => (b ? gcd(b, a % b) : a);

/** A stride through the list that visits every thought once per round, jumping around so similar ones don't bunch up. */
function stride(n: number): number {
  let s = Math.round(n * 0.382); // the golden-ratio jump spreads neighbours far apart
  while (gcd(s, n) !== 1) s++;
  return s;
}
const STRIDE = stride(DAILY_THOUGHTS.length);

/** Today's thought — the same all day, different each day, no repeats until the list runs out. */
export function thoughtForDate(date: Date = new Date()): Thought {
  const n = DAILY_THOUGHTS.length;
  const day = ((localDayNumber(date) % n) + n) % n;
  return DAILY_THOUGHTS[(day * STRIDE) % n];
}
