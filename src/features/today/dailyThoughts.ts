/** Days since a fixed start, counted on the LOCAL calendar (so it changes at your midnight). */
function localDayNumber(date: Date): number {
  return Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
}

/** Today's thought — the same all day, different each day, no repeats until the list runs out. */
export function thoughtForDate(date: Date = new Date()): string {
  const index = ((localDayNumber(date) % DAILY_THOUGHTS.length) + DAILY_THOUGHTS.length) % DAILY_THOUGHTS.length;
  return DAILY_THOUGHTS[index];
}
